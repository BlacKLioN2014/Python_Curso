#set vacio
conjunto_vacio = set()
print(conjunto_vacio)
                                                            #En conjunto no puede haber valores repetidos, en caso de haber, se omiten por ejemplo en un print
#primera forma de crear set
conjunto_numerico = set([1, 2, 3, 4])
print(conjunto_numerico)

#segunda forma de crear set
conjunto_numerico = {1, 2 , 3, 4, 5, 6}
print(conjunto_numerico)

conjunto_texto = {'Manzana', 'Banana', 'cereza'}
print(conjunto_texto)
                                                            #En un conjunto, los elementos son ordenados en automatico en una print
conjunto_mixto = {1, 'dos', True, 3.5}
print(conjunto_mixto)

conjunto_boleano = {True, False,1,0,2}
print(conjunto_boleano)
