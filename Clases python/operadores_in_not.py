colores = ['Amarillo', 'Azul', 'Verde', 'Rojo', 'Gris', 'Negro']

#in: permite saber si existe un elemento dentro de la lista, y retorna un valor booleano
print('Verde' in colores)
print('Violeta' in colores)

#not in: permite saber si no existe un elemento dentro de la lista, y retorna un valor booleano
print('Verde' not in colores)
print('Violeta' not in colores)

